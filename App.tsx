                      <span style={{width:32,height:32,borderRadius:8,background:"rgba(201,162,39,0.2)",border:`1px solid ${G.gold}44`,color:G.gold,fontSize:12,fontWeight:900,display:"flex",alignItems:"center",justifyContent:"center",flexShrink:0}}>{i+1}</span>
